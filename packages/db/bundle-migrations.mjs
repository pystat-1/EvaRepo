// Embeds ./migrations/*.sql into src/migrations.ts (the app has no file
// system access to its own source, so migrations ship as strings).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync(new URL("./migrations/", import.meta.url))
  .filter((f) => f.endsWith(".sql"))
  .sort();
const items = files.map((f) => {
  const sql = readFileSync(new URL(`./migrations/${f}`, import.meta.url), "utf8");
  return `  { name: ${JSON.stringify(f.replace(/\.sql$/, ""))}, sql: ${JSON.stringify(sql)} },`;
});
writeFileSync(
  new URL("./src/migrations.ts", import.meta.url),
  `// GENERATED by bundle-migrations.mjs from ./migrations — do not edit.\nimport type { Migration } from "./migrate";\n\nexport const MIGRATIONS: Migration[] = [\n${items.join("\n")}\n];\n`
);
console.log(`bundled ${files.length} migration(s)`);
